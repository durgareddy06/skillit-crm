function slugify(value) {
  return String(value || "student")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 24) || "student";
}

function formatPhone(phone) {
  if (!phone) return "+91 98765 43210";
  return String(phone);
}

